export const OPEN_DESTINATIONS = DESTINATIONS.filter((d) => d.status === 'open')

export function getDestination(slug: string): Destination | undefined {
  return DESTINATIONS.find((d) => d.slug === slug)
}

const norm = (s: string) => s.toLowerCase().replace(/["'״׳.\-_]/g, '').replace(/\s+/g, ' ').trim()

/**
 * השרת שומר "arrivalAirport" כמחרוזת חופשית. מנסים להתאים אותה ליעד בקטלוג:
 * שם בעברית, שם באנגלית או קוד. לא נמצא? מחזירים undefined והתצוגה תהיה כללית.
 */
export function resolveDestination(airport: string | undefined | null): Destination | undefined {
  if (!airport) return undefined
  const a = norm(airport)
  return DESTINATIONS.find((d) => d.aliases.some((al) => a === norm(al) || a.includes(norm(al))))
}
